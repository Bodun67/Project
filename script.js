const catButton = document.querySelector('#cat-button');
const catSpeech = document.querySelector('#cat-speech');
const bonusFill = document.querySelector('#bonus-fill');
const bonusLabel = document.querySelector('#bonus-label');
const languageSwitch = document.querySelector('#language-switch');
const bonusKey = 'osinnia-kava-bonus-date';
const languageKey = 'osinnia-kava-language';
const today = new Intl.DateTimeFormat('en-CA').format(new Date());
let currentLanguage = localStorage.getItem(languageKey) === 'en' ? 'en' : 'uk';

function renderMenu() {
  const languageIndex = currentLanguage === 'uk' ? 0 : 1;
  for (const [group, items] of Object.entries(menu)) {
    const container = document.querySelector(`#${group}-menu`);
    container.innerHTML = items.map((item) => `
      <article class="menu-card${item.featured ? ' featured' : ''}">
        <div class="card-top"><span class="card-icon" aria-hidden="true">${item.icon}</span><span class="tag">${item.tag[languageIndex]}</span></div>
        <h3>${item.name[languageIndex]}</h3><p>${item.text[languageIndex]}</p>
        <div class="price">${item.price} <small>₴</small></div>
      </article>`).join('');
  }
}

function updateBonus(messageKey) {
  const t = translations[currentLanguage];
  const claimed = localStorage.getItem(bonusKey) === today;
  bonusFill.style.width = claimed ? '100%' : '0%';
  bonusLabel.textContent = claimed ? t.bonusDone : t.bonusEmpty;
  catSpeech.textContent = messageKey ? t[messageKey] : (claimed ? t.catClaimed : t.catPrompt);
}

function applyLanguage() {
  const t = translations[currentLanguage];
  document.documentElement.lang = currentLanguage;
  document.title = currentLanguage === 'uk' ? 'Осіння Кава — затишок у кожній чашці' : 'Autumn Coffee — comfort in every cup';
  document.querySelector('meta[name="description"]').content = currentLanguage === 'uk' ? 'Осіння Кава — затишна кав’ярня, сезонне меню та щоденний бонус від котика.' : 'Autumn Coffee — a cosy café, seasonal menu and a daily cat bonus.';
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = t[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = t[element.dataset.i18nPlaceholder];
  });
  languageSwitch.textContent = currentLanguage === 'uk' ? 'EN' : 'UA';
  languageSwitch.setAttribute('aria-label', currentLanguage === 'uk' ? 'Switch to English' : 'Перейти українською');
  document.querySelector('.brand').setAttribute('aria-label', currentLanguage === 'uk' ? 'Осіння Кава, на головну' : 'Autumn Coffee, home');
  document.querySelector('.nav').setAttribute('aria-label', currentLanguage === 'uk' ? 'Головна навігація' : 'Main navigation');
  catButton.setAttribute('aria-label', t.catAria);
  renderMenu();
  updateBonus();
}

function playPurr() {
  const AudioContextClass = window.AudioContext || window.webkitAudioContext;
  if (!AudioContextClass) return;
  const context = new AudioContextClass();
  const master = context.createGain();
  const pulse = context.createOscillator();
  const pulseDepth = context.createGain();
  const low = context.createOscillator();
  const warm = context.createOscillator();
  const now = context.currentTime;

  low.type = 'sine'; low.frequency.setValueAtTime(52, now);
  warm.type = 'triangle'; warm.frequency.setValueAtTime(104, now);
  pulse.type = 'sine'; pulse.frequency.setValueAtTime(24, now);
  master.gain.setValueAtTime(0.0001, now);
  master.gain.exponentialRampToValueAtTime(0.055, now + 0.05);
  master.gain.setValueAtTime(0.055, now + 0.7);
  master.gain.exponentialRampToValueAtTime(0.0001, now + 1.15);
  pulseDepth.gain.setValueAtTime(0.018, now);
  pulse.connect(pulseDepth).connect(master.gain);
  low.connect(master); warm.connect(master); master.connect(context.destination);
  low.start(now); warm.start(now); pulse.start(now);
  low.stop(now + 1.2); warm.stop(now + 1.2); pulse.stop(now + 1.2);
  setTimeout(() => context.close(), 1400);
}

catButton.addEventListener('click', () => {
  playPurr();
  catButton.classList.remove('celebrate');
  void catButton.offsetWidth;
  catButton.classList.add('celebrate');
  setTimeout(() => catButton.classList.remove('celebrate'), 1100);

  if (localStorage.getItem(bonusKey) === today) {
    updateBonus('catTomorrow');
    return;
  }
  localStorage.setItem(bonusKey, today);
  updateBonus('catClaimed');
});

languageSwitch.addEventListener('click', () => {
  currentLanguage = currentLanguage === 'uk' ? 'en' : 'uk';
  localStorage.setItem(languageKey, currentLanguage);
  applyLanguage();
});

