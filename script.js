const catButton = document.querySelector('#cat-button');
const catSpeech = document.querySelector('#cat-speech');
const bonusFill = document.querySelector('#bonus-fill');
const bonusLabel = document.querySelector('#bonus-label');
const bonusBalance = document.querySelector('#bonus-balance');
const bonusTotal = document.querySelector('#bonus-total');
const bonusStreak = document.querySelector('#bonus-streak');
const purrAudio = document.querySelector('#purr-audio');
const languageSwitch = document.querySelector('#language-switch');
const bonusKey = 'osinnia-kava-bonus-date';
const bonusHistoryKey = 'osinnia-kava-bonus-history';
const languageKey = 'osinnia-kava-language';
const today = new Intl.DateTimeFormat('en-CA').format(new Date());
let currentLanguage = localStorage.getItem(languageKey) === 'en' ? 'en' : 'uk';
let purrStopTimer;

function renderMenu() {
  const languageIndex = currentLanguage === 'uk' ? 0 : 1;
  const t = translations[currentLanguage];
  for (const [group, items] of Object.entries(menu)) {
    const container = document.querySelector(`#${group}-menu`);
    container.innerHTML = items.map((item) => `
      <button class="menu-card${item.featured ? ' featured' : ''}" type="button" aria-pressed="false" aria-label="${t.showPhoto}: ${item.name[languageIndex]}">
        <span class="menu-card-face">
          <span class="card-top"><span class="card-icon" aria-hidden="true">${item.icon}</span><span class="tag">${item.tag[languageIndex]}</span></span>
          <h3>${item.name[languageIndex]}</h3><p>${item.text[languageIndex]}</p>
          <span class="price">${item.price} <small>₴</small></span><span class="photo-hint">${t.showPhoto} ↗</span>
        </span>
        <span class="menu-photo"><img src="assets/menu/${item.image}" alt="${item.name[languageIndex]}" loading="lazy" /><span class="menu-photo-caption"><strong>${item.name[languageIndex]}</strong><small>${t.hidePhoto}</small></span></span>
      </button>`).join('');
  }
}

function getBonusHistory() {
  let history = [];
  try { history = JSON.parse(localStorage.getItem(bonusHistoryKey) || '[]'); } catch { history = []; }
  const legacyDate = localStorage.getItem(bonusKey);
  if (legacyDate && !history.includes(legacyDate)) history.push(legacyDate);
  return [...new Set(history)].sort();
}

function getStreak(history) {
  const claimed = new Set(history);
  const cursor = new Date(`${today}T12:00:00`);
  let streak = 0;
  while (claimed.has(new Intl.DateTimeFormat('en-CA').format(cursor))) {
    streak += 1;
    cursor.setDate(cursor.getDate() - 1);
  }
  return streak;
}

function updateBonus(messageKey) {
  const t = translations[currentLanguage];
  const history = getBonusHistory();
  const claimed = history.includes(today);
  bonusFill.style.width = claimed ? '100%' : '0%';
  bonusLabel.textContent = claimed ? t.bonusDone : t.bonusEmpty;
  catSpeech.textContent = messageKey ? t[messageKey] : (claimed ? t.catClaimed : t.catPrompt);
  bonusBalance.textContent = claimed ? 1 : 0;
  bonusTotal.textContent = history.length;
  bonusStreak.textContent = getStreak(history);
}

function applyLanguage() {
  const t = translations[currentLanguage];
  document.documentElement.lang = currentLanguage;
  document.title = currentLanguage === 'uk' ? 'Осіння Кава — затишок у кожній чашці' : 'Autumn Coffee — comfort in every cup';
  document.querySelector('meta[name="description"]').content = currentLanguage === 'uk' ? 'Осіння Кава — затишна кав’ярня, сезонне меню та щоденний бонус від котика.' : 'Autumn Coffee — a cosy café, seasonal menu and a daily cat bonus.';
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = t[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = t[element.dataset.i18nPlaceholder];
  });
  languageSwitch.textContent = currentLanguage === 'uk' ? 'EN' : 'UA';
  languageSwitch.setAttribute('aria-label', currentLanguage === 'uk' ? 'Switch to English' : 'Перейти українською');
  document.querySelector('.brand').setAttribute('aria-label', currentLanguage === 'uk' ? 'Осіння Кава, на головну' : 'Autumn Coffee, home');
  document.querySelector('.nav').setAttribute('aria-label', currentLanguage === 'uk' ? 'Головна навігація' : 'Main navigation');
  catButton.setAttribute('aria-label', t.catAria);
  renderMenu();
  updateBonus();
}

function playPurr() {
  clearTimeout(purrStopTimer);
  purrAudio.pause();
  purrAudio.currentTime = 0;
  purrAudio.volume = 0.72;
  purrAudio.play().catch(() => {});
  purrStopTimer = setTimeout(() => {
    purrAudio.pause();
    purrAudio.currentTime = 0;
  }, 3300);
}

catButton.addEventListener('click', () => {
  playPurr();
  catButton.classList.remove('celebrate');
  void catButton.offsetWidth;
  catButton.classList.add('celebrate');
  setTimeout(() => catButton.classList.remove('celebrate'), 1100);

  const history = getBonusHistory();
  if (history.includes(today)) {
    updateBonus('catTomorrow');
    return;
  }
  localStorage.setItem(bonusKey, today);
  history.push(today);
  localStorage.setItem(bonusHistoryKey, JSON.stringify([...new Set(history)].sort()));
  updateBonus('catClaimed');
});

document.querySelector('#menu').addEventListener('click', (event) => {
  const card = event.target.closest('.menu-card');
  if (!card) return;
  const willOpen = !card.classList.contains('is-photo');
  document.querySelectorAll('.menu-card.is-photo').forEach((openCard) => {
    openCard.classList.remove('is-photo');
    openCard.setAttribute('aria-pressed', 'false');
  });
  if (willOpen) {
    card.classList.add('is-photo');
    card.setAttribute('aria-pressed', 'true');
  }
});

function initLeaves() {
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const container = document.querySelector('#falling-leaves');
  const colors = ['#d98245', '#f0b45d', '#a94c2c', '#e8c06a', '#b86536'];
  const shapes = ['🍂', '🍁', '❧'];
  for (let index = 0; index < 19; index += 1) {
    const leaf = document.createElement('span');
    leaf.className = 'falling-leaf';
    leaf.textContent = shapes[index % shapes.length];
    leaf.style.setProperty('--leaf-x', `${(index * 17 + Math.random() * 12) % 100}%`);
    leaf.style.setProperty('--leaf-size', `${13 + Math.random() * 16}px`);
    leaf.style.setProperty('--leaf-color', colors[index % colors.length]);
    leaf.style.setProperty('--leaf-duration', `${9 + Math.random() * 8}s`);
    leaf.style.setProperty('--leaf-delay', `${-Math.random() * 15}s`);
    const drift = -70 + Math.random() * 140;
    leaf.style.setProperty('--leaf-drift', `${drift}px`);
    leaf.style.setProperty('--leaf-drift-end', `${drift * -0.45}px`);
    container.append(leaf);
  }
}

